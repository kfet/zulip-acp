// Package schemadoc generates the config key reference
// (internal/config/schema_gen.go) from the doc comments of the config
// structs, so the reference that `zulip-acp config-schema` prints
// cannot drift from the code. A test fails when the checked-in file is
// stale; `go generate ./internal/config` rewrites it.
package schemadoc

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

// Root is the struct the reference starts from.
const Root = "Config"

// Field is one documented config key.
type Field struct{ Key, Type, Doc string }

// Generate parses the non-test Go files in dir and returns the source
// of schema_gen.go.
func Generate(dir string) ([]byte, error) {
	fields, err := Fields(dir)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/config/schemadoc; DO NOT EDIT.\n\npackage config\n\n")
	b.WriteString("// Schema documents every config key, in file order.\nvar Schema = []SchemaField{\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "\t{Key: %s, Type: %s, Doc: %s},\n", strconv.Quote(f.Key), strconv.Quote(f.Type), strconv.Quote(f.Doc))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// Fields returns every json key reachable from Root, nested keys
// dotted ("delete.bot_email", "quick_models[].emoji").
func Fields(dir string) ([]Field, error) {
	fset := token.NewFileSet()
	paths, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	sort.Strings(paths)
	structs := map[string]*ast.StructType{}
	for _, p := range paths {
		if strings.HasSuffix(p, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, p, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		ast.Inspect(f, func(n ast.Node) bool {
			if ts, ok := n.(*ast.TypeSpec); ok {
				if st, ok := ts.Type.(*ast.StructType); ok {
					structs[ts.Name.Name] = st
				}
			}
			return true
		})
	}
	root, ok := structs[Root]
	if !ok {
		return nil, fmt.Errorf("schemadoc: no struct %s in %s", Root, dir)
	}
	var out []Field
	if err := walk(fset, structs, root, "", &out); err != nil {
		return nil, err
	}
	return out, nil
}

// walk appends the keys of st. A field with no doc comment of its own
// shares the doc of the field on the line just above it: one comment
// over a block of related fields documents them all.
func walk(fset *token.FileSet, structs map[string]*ast.StructType, st *ast.StructType, prefix string, out *[]Field) error {
	prevDoc, prevLine := "", -1
	for _, f := range st.Fields.List {
		line := fset.Position(f.Pos()).Line
		doc := strings.Join(strings.Fields(f.Doc.Text()), " ")
		if doc == "" && line == prevLine+1 {
			doc = prevDoc
		}
		prevDoc, prevLine = doc, line
		if f.Tag == nil {
			continue
		}
		tag, _ := strconv.Unquote(f.Tag.Value)
		name, _, _ := strings.Cut(reflect.StructTag(tag).Get("json"), ",")
		if name == "" || name == "-" {
			continue
		}
		if doc == "" {
			return fmt.Errorf("schemadoc: config key %s%s has no doc comment", prefix, name)
		}
		var tb bytes.Buffer
		printer.Fprint(&tb, fset, f.Type)
		typ := strings.TrimPrefix(tb.String(), "*")
		elem, list := strings.CutPrefix(typ, "[]")
		if sub, ok := structs[elem]; ok {
			kind, next := "object", prefix+name+"."
			if list {
				kind, next = "list of objects", prefix+name+"[]."
			}
			*out = append(*out, Field{Key: prefix + name, Type: kind, Doc: doc})
			if err := walk(fset, structs, sub, next, out); err != nil {
				return err
			}
			continue
		}
		*out = append(*out, Field{Key: prefix + name, Type: typ, Doc: doc})
	}
	return nil
}
